"""Stage `datasheet` (reduce): the appendix datasheet (Gebru et al., 2021) and a Croissant RAI extension, filled with
numbers measured by the other WS1 stages. Statements that need the authors (not derivable from the data) are marked
`TODO(authors)` so they cannot slip into the paper unnoticed.

Reads (each optional; missing ones are listed in the output): describe.json, quality/flags_by_group.csv,
reconcile.json, provenance.json, keys.json, neardup summary.json, lexical-report tables.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from ..runtime import Context, stage


def _load(path: Path):
    if not path.exists():
        return None
    return pd.read_csv(path) if path.suffix == ".csv" else json.loads(path.read_text())


def _pct(x) -> str:
    return "n/a" if x is None else f"{x:.2%}"


@stage("ws1", "datasheet", needs=("describe", "quality", "reconcile", "provenance", "keys"),
       help="datasheet (Gebru et al.) + Croissant RAI metadata from the measured numbers")
def run(ctx: Context) -> dict:
    sd = ctx.cfg.stage_dir
    d = _load(sd("ws1", "describe") / "describe.json") or {}
    q = _load(sd("ws1", "quality") / "flags_by_group.csv")
    rc = _load(sd("ws1", "reconcile") / "reconcile.json") or {}
    pv = _load(sd("ws1", "provenance") / "provenance.json") or {}
    ky = _load(sd("ws1", "keys") / "keys.json") or {}
    nd = _load(sd("ws1", "neardup") / "summary.json") or {}
    missing = [n for n, v in (("describe", d), ("quality", q), ("reconcile", rc), ("provenance", pv), ("keys", ky))
               if v is None or (isinstance(v, dict) and not v)]

    def flag(key: str) -> str:
        if q is None:
            return "n/a"
        r = q[(q.group == "all") & (q.flag == key)]
        return "n/a" if r.empty else f"{r.rate.iloc[0]:.2%} [{r.lo.iloc[0]:.2%}, {r.hi.iloc[0]:.2%}]"

    models = ", ".join(m["m"] for m in pv.get("models", [])) or "n/a"
    est = " (estimated from the debug sample)" if ctx.cfg.profile != "full" else ""
    lines = [
        "# Datasheet: laion/Scientific-Summaries" + est, "",
        f"Revision `{ctx.cfg.data.revision}`. Generated by `alexandria ws1 datasheet` "
        f"(profile `{ctx.cfg.profile}`); every number below is measured unless marked TODO(authors).", "",
        "## Motivation",
        "- **Purpose.** Structured, LLM-written summaries of scientific papers (18 fields) for retrieval, claim "
        "verification and knowledge-dense pretraining. TODO(authors): funding and creators statement.", "",
        "## Composition",
        f"- **Instances.** One summary per paper; {rc.get('corpus_rows', 'n/a'):,} rows in "
        f"{rc.get('corpus_shards', 'n/a'):,} shards across arxiv, bethgelab, pubmed and web-papers."
        if isinstance(rc.get("corpus_rows"), int) else "- **Instances.** n/a",
        f"- **Analysed here.** {d.get('papers', 'n/a'):,} papers: "
        + ", ".join(f"{g} {n:,}" for g, n in sorted((d.get('papers_by_group') or {}).items())) + "."
        if isinstance(d.get("papers"), int) else "- **Analysed here.** n/a",
        "- **Fields.** 44 columns: 7 source metadata, 18 summary fields, 3 generation metadata, 13 OpenAlex, 3 text. "
        f"Column names are canonical in every shard ({len(ky.get('non_canonical_columns', [])) if ky else 'n/a'} "
        "non-canonical names); types differ between shards and are unified by casting.",
        f"- **Discipline labels** are free text: {d.get('field_labels_raw', 'n/a')} distinct coarse labels "
        f"({d.get('field_labels_clean', 'n/a')} after merging spelling variants); mapped onto 10 domains.",
        f"- **Missing metadata.** {d.get('year_missing', 'n/a')} papers without a year; OpenAlex match rate per group: "
        + ", ".join(f"{g} {_pct(v)}" for g, v in sorted((d.get('openalex_match') or {}).items())) + ".",
        f"- **Duplicates.** Paper-level (KU-Fixes, strong): {flag('dup_strong')}; "
        f"near-identical summaries of different papers: {nd.get('new_docs_share', 'see neardup stage')}.",
        f"- **Retracted papers** (OpenAlex): {d.get('retracted', 'n/a')}.", "",
        "## Collection process",
        f"- **Summarizer.** {models}. Prompt published: {'yes' if pv.get('prompt_published') else 'TODO(authors)'}; "
        f"temperature: {pv.get('temperature') if pv.get('temperature') is not None else 'TODO(authors)'}.",
        f"- **Tokens.** {pv.get('tokens_in', 0):,.0f} input / {pv.get('tokens_out', 0):,.0f} output"
        f"{' (extrapolated)' if pv.get('scale', 1) != 1 else ''}; estimated API cost "
        f"{('USD %s' % format(round(pv['cost_usd_estimate']), ',')) if pv.get('cost_usd_estimate') else 'n/a'}.",
        "- **Input.** Full text when available, else metadata + abstract; source text clipped at 100,000 characters "
        f"({d.get('input_truncated', 'n/a')} papers clipped).",
        f"- **Failure rate.** {_pct(pv['failures'][-1]['rate']) if pv.get('failures') else 'n/a'} of generations "
        "need regeneration, refused, produced unparsable claims or hit the output cap.", "",
        "## Known quality issues (WS1)",
        f"- Summary does not match its paper: {flag('wrong_paper')}.",
        f"- Summarized from unreadable source text (PDF font mojibake): {flag('garbled_source')}.",
        f"- A core prose field empty or a placeholder: {flag('core_missing')}.",
        f"- A prose field ends mid-sentence: {flag('truncated_field')}.",
        f"- Refusal or 'as an AI' boilerplate: {flag('refusal')}.",
        f"- A core field anomalously short / long for its input type: {flag('len_short')} / {flag('len_long')}.",
        "- Delivered field lengths are about half of the README targets (see quality/length_vs_documented.csv).",
        f"- Summarized from metadata + abstract only: {flag('abstract_only')}.", "",
        "## Preprocessing / cleaning",
        "- KU-Fixes repairs placeholder titles/authors from OpenAlex and misspelled claim keys; WS1's shared "
        "normalizer (`alexandria.schema.load_summary`) applies the reviewed alias table and nulls placeholders.", "",
        "## Uses",
        "- Recommended: retrieval, claim verification research, knowledge-dense pretraining with the quality flags "
        "as filters. Not recommended: clinical or policy decisions without the original paper.", "",
        "## Distribution and maintenance",
        "- CC-BY-4.0 (Hugging Face). TODO(authors): maintainer contact, erratum and versioning policy.", "",
    ]
    if missing:
        lines += ["", f"_Inputs not yet available when this was generated: {', '.join(missing)}._"]
    (ctx.out / "datasheet.md").write_text("\n".join(lines) + "\n")

    croissant_src = ctx.cfg.site.data_root / "croissant.json"
    rai = {
        "rai:dataCollection": f"LLM-generated structured summaries ({models}) of scientific papers; "
                              "metadata from OpenAlex.",
        "rai:dataCollectionMissingData": f"{d.get('year_missing', 'n/a')} papers without a year in the analysed set; "
                                         "OpenAlex unmatched for part of each subset.",
        "rai:dataLimitations": f"wrong-paper summaries {flag('wrong_paper')}; summaries of unreadable sources "
                               f"{flag('garbled_source')}; empty/placeholder core fields {flag('core_missing')}.",
        "rai:dataBiases": "TODO(authors): disciplinary and language coverage (see describe stage distributions).",
        "rai:personalSensitiveInformation": "Author names and affiliations from public scholarly metadata.",
        "rai:dataUseCases": "retrieval, claim verification, knowledge-dense pretraining",
    }
    out = {"base": str(croissant_src) if croissant_src.exists() else None, "rai": rai}
    ctx.write_json("croissant_rai.json", out)
    ctx.publish("Datasheet", [
        {"type": "markdown", "text": "\n".join(lines)},
        {"type": "markdown", "text": "Files: `datasheet.md`, `croissant_rai.json` (merge into croissant.json)."},
    ], summary="Generated from measured numbers; TODO(authors) marks statements the data cannot provide.")
    return {"missing_inputs": missing, "todo": sum(line.count("TODO(authors)") for line in lines)}
